@router.get("/{investigation_id}/report", response_model=APIResponse, summary="Get compiled investigation report")
async def get_investigation_report(
    investigation_id: str,
    session_repo: SessionRepository = Depends(get_session_repository)
) -> APIResponse:
    """Retrieve markdown executive report synthesized by Reporter agent."""
    session = await session_repo.get(investigation_id)
    if not session:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Investigation '{investigation_id}' not found."
        )
    # session.report may be a Pydantic model or a plain dict (deserialized from JSON on disk)
    report = session.report
    if report is None:
        report_data = None
    elif isinstance(report, dict):
        report_data = report
    else:
        report_data = report.model_dump(mode="json")
    return APIResponse(
        status="success",
        data={"report": report_data}
    )

